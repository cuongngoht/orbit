import assert from 'node:assert/strict';
import { test } from 'node:test';
import { copyFileSync } from 'node:fs';
import { join } from 'node:path';
import { fixture } from './fixture.mjs';
import { agenticHosts } from '../src/agentic-hosts/read.mjs';
import { ROUTES } from '../src/router.mjs';
import { hostStore } from '../../src/host/store.mjs';
test('host visibility distinguishes observed, available and desired without guessing health', (t) => {
  const { root, ctx } = fixture(t);
  copyFileSync(new URL('../../catalog/hosts.json', import.meta.url), join(root.plugin, 'catalog/hosts.json'));
  const store = hostStore(ctx.world.rooms, ctx.world.io, 'codex');
  store.observe({ protocol: 2, engineVersion: '1.6.3', event: 'session-start' });
  store.update({ host_memory: true }, 0);
  ctx.world.env.CLAUDE_PLUGIN_OPTION_TRACE = 'false';
  const result = agenticHosts(ctx);
  assert.equal(result.hosts.length, 4);
  const grok = result.hosts.find((h) => h.id === 'grok');
  assert.equal(grok.observed, false, 'Grok Build (1.8.9) is listed, and nothing claims it was seen');
  assert.equal(grok.health, 'unknown');
  const native = result.hosts.find((h) => h.id === 'codex');
  assert.equal(native.observed, true);
  assert.equal(native.installed, 'unknown');
  assert.equal(native.health, 'unknown');
  assert.equal(native.version, null);
  assert.equal(native.desired.host_memory, true);
  assert.equal(native.effective.host_memory, false);
  assert.equal(native.effective.trace, true);
  assert.equal(result.hosts.find((h) => h.id === 'claude').effective.trace, false);
  assert.equal(result.hosts.find((h) => h.id === 'antigravity').effective.prompt_router, false);
  const routes = ROUTES.filter((r) => r.path.test('/api/v1/agentic-hosts'));
  assert.deepEqual(routes.map((r) => r.method), ['GET']);
  assert.ok(routes.every((r) => !r.mutates));
});
