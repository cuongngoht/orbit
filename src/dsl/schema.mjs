// The editor's schema, GENERATED from the EFFECTIVE vocabulary.
//
// A hand-written schema drifts from the validator the moment someone adds a
// verb to one and not the other -- it happened with `as` and `identities`.
// So the schema is not a source; it is an output. `node cli/schema.mjs --write`
// refreshes <project>/ui-tests/schema/case.schema.json and `query check` warns when
// the file on disk is older than this generator says it should be.
//
// It takes a REGISTRY rather than reading the tables, so a project whose
// extensions added a field gets a schema that knows about it -- the same schema
// its validator and its runner are working from. Passing nothing means the
// engine's own vocabulary, which is what `node cli/schema.mjs` prints.

import { IDENTITY_FIELDS, PARAM_FIELDS, RESOLVE_FIELDS, ROOT_FIELDS, ROOT_REQUIRED } from "./core/fields.mjs";
import { CORE } from "./registry.mjs";

// `doc` becomes the editor's description; `says`, `esc` and `literal` are the
// engine's own (constraints.mjs, escape.mjs, registry.mjs) and must never reach
// a published schema.
const strip = ({ doc, says, esc, literal, ...schema }) => ({ ...schema, description: doc });
const properties = (table) => Object.fromEntries(Object.entries(table).map(([k, v]) => [k, strip(v)]));

export function caseSchema(dsl = CORE) {
  return {
    $schema: "http://json-schema.org/draft-07/schema#",
    $id: "https://orbit/drive-ui/case.schema.json",
    title: "UI test case (orbit)",
    description: "One whole task driven against the live UI through playwright-cli. GENERATED by orbit from src/dsl/core/{fields,verbs}.mjs plus this project's registered extensions — edit those, then `node cli/schema.mjs --write`. Shape lives here; the rules a shape cannot express live in src/dsl/rules/.",
    type: "object",
    required: ROOT_REQUIRED,
    additionalProperties: false,
    properties: properties(ROOT_FIELDS),
    definitions: { identity: object(IDENTITY_FIELDS, []), resolve: object(RESOLVE_FIELDS, ["as", "sql"]), param: object(PARAM_FIELDS, ["n"]), step: stepSchema(dsl) },
  };
}

const object = (table, required) => ({ type: "object", required, additionalProperties: false, properties: properties(table) });

function stepSchema(dsl) {
  const verbs = dsl.verbs();
  const doField = { enum: verbs.map((v) => v.name), description: verbs.map((v) => `${v.name}: ${v.doc}.`).join(" ") };
  const props = { ...properties(dsl.fields()), do: doField };
  return { type: "object", required: ["do"], additionalProperties: false, properties: props, allOf: verbs.map((v) => perVerb(v, dsl)) };
}

// Per verb: only its own fields plus the common ones may appear, and what it
// needs must be present. Expressed as if/then so an editor points at the verb.
function perVerb(v, dsl) {
  const allowed = [...dsl.commonFields(), ...v.fields];
  return { if: { properties: { do: { const: v.name } } }, then: { propertyNames: { enum: allowed }, allOf: v.needs.map(need) } };
}

const need = (n) => (Array.isArray(n) ? { anyOf: n.map((k) => ({ required: [k] })) } : { required: [n] });
