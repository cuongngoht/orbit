// The editor's schema for a test plan, GENERATED from qa/fields.mjs the same way
// the case schema is generated from dsl/fields.mjs. It is an OUTPUT, never a
// source: `node cli/schema.mjs --write` refreshes <project>/ui-tests/schema/plan.schema.json
// and `query check` reports a copy that has fallen behind the vocabulary.
import { DEFINITIONS, PLAN_FIELDS, PLAN_REQUIRED, SCHEMA_VERSION } from "./fields.mjs";

// `doc` becomes the description; `says` and `esc` are the engine's own and must
// never reach a published schema.
const strip = ({ doc, says, esc, ...schema }) => ({ ...schema, description: doc });
const properties = (table) => Object.fromEntries(Object.entries(table).map(([k, v]) => [k, strip(v)]));

const object = (table, required) => ({ type: "object", required, additionalProperties: false, properties: properties(table) });

const definitions = () => Object.fromEntries(Object.entries(DEFINITIONS).map(([k, d]) => [k, object(d.table, d.required)]));

export function planSchema() {
  return {
    $schema: "http://json-schema.org/draft-07/schema#",
    $id: "https://orbit/drive-ui/plan.schema.json",
    title: "QA test plan (orbit)",
    description: `One feature's test plan as data, version ${SCHEMA_VERSION}. GENERATED by orbit from src/qa/{fields,vocab}.mjs — edit those, then \`node cli/schema.mjs --write\`. The Markdown beside it is rendered from this file; this one is the source. Shape lives here; the rules a shape cannot express live in src/qa/rules/.`,
    type: "object",
    required: PLAN_REQUIRED,
    additionalProperties: false,
    properties: properties(PLAN_FIELDS),
    definitions: definitions(),
  };
}
